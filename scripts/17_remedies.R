# 17 — 【已退役 / DEPRECATED，仅保留记录】
#
# 本脚本原本负责"对策规则检验"，但它建立在两处已确认有问题的基础上：
#   (a) 旧 C-index 评价（summary(coxph(Surv~s))$concordance）在评价集上重新
#       拟合、方向由评价数据决定 —— 在测试集上构成泄漏；
#   (b) 旧数据管线只落盘 C-index、没有逐患者预测，因此无法做需要重采样验证集的规则。
#
# 其功能已全部并入修正后的管线，规则逻辑只保留【一处】，避免两份实现分叉：
#
#   数据生成   scripts/19_main_corrected.R   → results/main/19_<队列>_<种子>_100.rds
#                                            （逐患者训练/验证/测试预测）
#   规则与核算 scripts/20_analysis_corrected.R
#
# ------------------------------------------------------------------
# 评审指出的 4 个具体问题，逐条说明修在哪里：
#
# 1. 【跨队列配对的对象错误】
#    原文：`ag` 已按 rule 聚合（无 cohort 列），却又按 `base$cohort` 匹配，
#          无法实现逐队列配对。
#    修在：20_analysis_corrected.R 的 P2 段 —— 直接从逐基因集明细 `A`
#          用 `match(d$geneset, ref_r$geneset)` 做键连接，先算配对差再聚合；
#          参照是【同队列、同划分、同基因集】的 argmax_val，不再只与 Lasso 比。
#
# 2. 【方向学习】
#    原文：`sgn` 与 `pmax(v, 1-v)` 在评价集上推断方向，无法证明方向只由验证集决定。
#    修在：20 与 19 统一采用固定约定（高值 = 高风险）+ 直接评价
#          `concordance(Surv ~ s, reverse = TRUE, timewt = "n")`；
#          19 额外输出【训练集】C-index 作为方向诊断（实测 16 个候选全部 > 0.5）。
#
# 3. 【用单边阈值自动判定"偏倚消除"】
#    原文：`sel_bias < 0.005` 即判为消除；很大的负偏差也会通过。
#    修在：删除该自动标签。20 的 P2 段只报告配对差、95% 区间与 p 值，
#          并明确注明"差异不显著 != 等效或非劣；点估计接近零 != 已证实消除偏倚"。
#
# 4. 【集成内部标准化的定位】
#    原文未说明集成中标准化参数从哪里来。
#    修在：20 的 `ens_pred()` —— 均值/标准差只用【验证集预测】估计，
#          再固定应用到测试集，属于验证阶段构建集成，已在注释中写明。
#
# 此外，本脚本原先还包含 MESO 上 `worst_half`/`penalized` 两条规则"结构上不可算"
# 的处理。修正版不再把它们说成"C-index 数学上不可计算"，而是如实报告
# 每组（队列×划分）的验证集样本数与【可比对生存对数】——见 20_coverage.tsv。
# ============================================================

cat("本脚本已退役。对策规则的修正版实现在：\n")
